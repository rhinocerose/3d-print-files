#!/usr/bin/env python3
"""
Linux/macOS version of scripts/Update-Readmes.ps1 (standard library only, Python 3.8+).

Generates a README.md in every category folder of this repo, with a preview image, a link
to the original model page, and a link to the repo folder for every build. Both scripts
produce byte-identical output and share scripts/readme-sources.json, so you can run either
one on any machine. Keep them in sync when changing either one.

Build detection:
  * Thingiverse  - folder has a README.txt "... on Thingiverse: <url>", or ends in a thing id
  * Printables   - folder ends in "-model_files" / contains "<id>-<slug>-<uuid>.pdf"
  * MakerWorld   - folder name contains "+" or ends in "_stls"
  * Anything else that holds model files is listed with an unknown source

Resolved sources are cached in scripts/readme-sources.json. Edit an entry there and set
"manual": true to override what the script found; manual entries are never refetched.

Usage:
  python3 scripts/update_readmes.py [--refresh] [--offline] [--list-only]
"""
import argparse
import glob
import hashlib
import json
import os
import posixpath
import re
import sys
import time
import urllib.parse
import urllib.request
import zipfile

# Every sub-folder that holds two or more build folders gets its own README, and its parent
# README links to it instead of listing those builds. Set to False to only split the
# folders in SPLIT_FOLDERS (and sub-folders inside them).
NEST_EVERYWHERE = True

# Folders (relative to the repo root, wildcards allowed) that always get their own README,
# even with a single build.
SPLIT_FOLDERS = [
    'storage/8020',
    'storage/systems/*',
]

# A README.md you wrote yourself (no "Generated by" line) is never overwritten: the build
# gallery is inserted between <!-- builds:start --> and <!-- builds:end --> at its end, and
# everything outside those markers is kept.

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CACHE_PATH = os.path.join(REPO, 'scripts', 'readme-sources.json')
IMG_DIR = 'readme-images'
UA = 'Mozilla/5.0 (3d-print-files readme generator)'

MODEL_EXT = {'.stl', '.3mf', '.step', '.stp', '.f3d', '.f3z', '.scad', '.obj', '.fcstd', '.skp', '.shapr',
             '.sldprt', '.3dm', '.ipt', '.iges', '.igs', '.gcode', '.dxf', '.zip', '.blend', '.amf'}
IMAGE_EXT = {'.jpg', '.jpeg', '.png', '.gif', '.webp'}
SKIP_DIRS = {'.git', 'scripts', IMG_DIR.lower(), '__macosx'}

GEN_MARKER = 'Generated by scripts/Update-Readmes.ps1'   # identifies generated files; don't change
SEC_START = '<!-- builds:start (generated by scripts/Update-Readmes.ps1) -->'
SEC_REGEX = re.compile(r'(?s)\r?\n?<!-- builds:start[^>]*-->.*?<!-- builds:end -->\r?\n?')
SITE_NAME = {'thingiverse': 'Thingiverse', 'printables': 'Printables', 'makerworld': 'MakerWorld'}

OFFLINE = False


# ---------------------------------------------------------------- helpers (mirror the .NET behaviour)
def okey(s):
    """Sort key equivalent to .NET StringComparer.OrdinalIgnoreCase."""
    return ''.join(c.upper() if len(c.upper()) == 1 else c for c in s)


def osort(items, key):
    return sorted(items, key=lambda x: okey(key(x)))   # sorted() is stable, like the PS version


def ext_of(name):   # [IO.Path]::GetExtension
    i = name.rfind('.')
    return '' if i < 0 or i == len(name) - 1 else name[i:]


def stem_of(name):  # [IO.Path]::GetFileNameWithoutExtension
    i = name.rfind('.')
    return name if i < 0 else name[:i]


def rel(full):
    return full[len(REPO):].lstrip(os.sep).replace(os.sep, '/')


def norm(s):
    return re.sub(r'[\W_]', '', s.lower()) if s else ''


def escape_data(s):  # [Uri]::EscapeDataString
    return urllib.parse.quote(s, safe="!*'()~")


def enc(rel_path):
    return '/'.join(escape_data(p) for p in rel_path.split('/'))


def html_enc(s):  # [System.Net.WebUtility]::HtmlEncode
    if not s:
        return ''
    out = []
    for ch in str(s):
        o = ord(ch)
        if ch == '<': out.append('&lt;')
        elif ch == '>': out.append('&gt;')
        elif ch == '&': out.append('&amp;')
        elif ch == '"': out.append('&quot;')
        elif ch == "'": out.append('&#39;')
        elif 160 <= o <= 255: out.append('&#%d;' % o)
        else: out.append(ch)
    return ''.join(out)


def pretty(s):
    t = re.sub(r'-model_files$', '', s, flags=re.I)
    t = re.sub(r'_stls$', '', t, flags=re.I).replace('+', ' ').replace('_', ' ')
    t = re.sub(r'\s+-\s+\d{5,}.*$', '', t, flags=re.I)
    t = re.sub(r'\s+\d{5,}$', '', t)
    if re.fullmatch(r'[a-z0-9 \-]+', t):   # slug-style -> Title Case
        t = ' '.join(w[0].upper() + w[1:] for w in re.split(r'\s+', t.replace('-', ' ')) if w)
    return re.sub(r'\s+', ' ', t).strip()


def read_text(path):  # [IO.File]::ReadAllText (BOM-aware, line endings untouched)
    with open(path, encoding='utf-8-sig', errors='replace', newline='') as f:
        return f.read()


def write_text(path, text):  # UTF-8 without BOM, line endings untouched
    with open(path, 'w', encoding='utf-8', newline='') as f:
        f.write(text)


_kids = {}


def kids(full):
    """(dirs, files) directly inside a folder, sorted by name."""
    if full not in _kids:
        dirs, files = [], []
        try:
            entries = list(os.scandir(full))
        except OSError:
            entries = []
        for e in osort(entries, lambda e: e.name):
            if e.is_dir():
                if e.name.lower() not in SKIP_DIRS:
                    dirs.append(e.path)
            else:
                files.append(e.path)
        _kids[full] = (dirs, files)
    return _kids[full]


def all_files(full):
    out = []
    for root, dirs, files in os.walk(full):
        for f in files:
            p = os.path.join(root, f)
            if '/__macosx/' not in p.replace(os.sep, '/').lower():
                out.append(p)
    return osort(out, lambda p: p.replace(os.sep, '/'))


def is_model(path): return ext_of(os.path.basename(path)).lower() in MODEL_EXT
def is_image(path): return ext_of(os.path.basename(path)).lower() in IMAGE_EXT


def tv_readme(full):
    rd = next((f for f in kids(full)[1] if os.path.basename(f).lower() == 'readme.txt'), None)
    if not rd:
        return None
    lines = re.split(r'\r\n|\n|\r', read_text(rd))
    for line in lines:   # current format: "<title> by <author> on Thingiverse: <url>"
        m = re.match(r'^\s*(.+?)\s+by\s+(.+?)\s+on Thingiverse:\s*(https?://\S*thingiverse\.com/thing:(\d+))', line, re.I)
        if m:
            return {'Name': m.group(1).strip(), 'Author': m.group(2).strip(),
                    'Url': re.sub(r'^http:', 'https:', m.group(3), flags=re.I), 'Id': m.group(4)}
    tid = name = author = None
    for line in lines:   # older format: "<url>" then "<title> by <author> is licensed under ..."
        if not tid:
            m = re.search(r'thingiverse\.com/thing:(\d+)', line, re.I)
            if m: tid = m.group(1)
        if not name:
            m = re.match(r'^\s*(.+?)\s+by\s+(.+?)\s+is licensed under', line, re.I)
            if m: name, author = m.group(1).strip(), m.group(2).strip()
    if tid:
        return {'Name': name, 'Author': author, 'Url': 'https://www.thingiverse.com/thing:' + tid, 'Id': tid}
    return None


def printables_pdf_id(full):
    for f in kids(full)[1]:
        m = re.match(r'^(\d+)-.+-[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\.pdf$', os.path.basename(f), re.I)
        if m:
            return m.group(1)
    return None


def source_hint(d):
    n = os.path.basename(d)
    if tv_readme(d): return 'thingiverse'
    if re.search(r'(?:_|\s-\s)(\d{5,8})(?:\s|$)', n) or re.search(r'_(\d{5,8})$', n): return 'thingiverse'
    if re.search(r'-model_files$', n, re.I) or re.search(r'-mo$', n, re.I) or printables_pdf_id(d): return 'printables'
    if '+' in n or (re.search(r'_stls$', n, re.I) and not re.match(r'^(legacy|old|new|v?\d+)_stls$', n, re.I)): return 'makerworld'
    return None


_marker = {}


def has_marker_below(d):
    if d not in _marker:
        _marker[d] = any(source_hint(c) or has_marker_below(c) for c in kids(d)[0])
    return _marker[d]


# ---------------------------------------------------------------- web lookups
def http_json(url, data=None, headers=None):
    h = {'User-Agent': UA}
    h.update(headers or {})
    if data is not None:
        data = json.dumps(data).encode('utf-8')
        h['Content-Type'] = 'application/json'
    req = urllib.request.Request(url, data=data, headers=h)
    with urllib.request.urlopen(req, timeout=60) as r:
        return json.loads(r.read().decode('utf-8'))


def download(url, out, headers=None):
    h = {'User-Agent': UA}
    h.update(headers or {})
    req = urllib.request.Request(url, headers=h)
    with urllib.request.urlopen(req, timeout=120) as r, open(out, 'wb') as f:
        while True:
            chunk = r.read(1 << 20)
            if not chunk:
                break
            f.write(chunk)


def gql(query, variables=None):
    time.sleep(0.25)
    body = {'query': query}
    if variables:
        body['variables'] = variables
    return http_json('https://api.printables.com/graphql/', body).get('data')


PRINT_FIELDS = 'id name slug user { publicUsername } image { filePath }'


def printables_info(p):
    img = None
    fp = (p.get('image') or {}).get('filePath')
    if fp:
        m = re.match(r'^(.*)/([^/]+)\.(\w+)$', fp)
        if m:
            img = 'https://media.printables.com/%s/thumbs/inside/640x480/%s/%s.webp' % (m.group(1), m.group(3), m.group(2))
    return {'source': 'printables', 'id': str(p['id']), 'name': p.get('name'),
            'author': (p.get('user') or {}).get('publicUsername'),
            'url': 'https://www.printables.com/model/%s-%s' % (p['id'], p.get('slug')), 'imageUrl': img}


def printables_by_id(pid):
    d = gql('query { print(id: "%s") { %s } }' % (pid, PRINT_FIELDS))
    return printables_info(d['print']) if d and d.get('print') else None


def printables_search(title, slug):
    q = re.sub(r'["\\]', ' ', title)
    d = gql('query { searchPrints2(query: "%s", limit: 20) { items { %s } } }' % (q, PRINT_FIELDS))
    for p in ((d or {}).get('searchPrints2') or {}).get('items') or []:
        if (slug and p.get('slug') == slug) or norm(p.get('name')) == norm(title):
            return printables_info(p)
    return None


def makerworld_cover(url):
    return url + '?x-oss-process=image/resize,w_640/format,webp' if url else None


def makerworld_search(title):
    time.sleep(0.4)
    kw = escape_data(title.replace('_', ' ').strip())
    r = http_json('https://makerworld.com/api/v1/search-service/select/design2?keyword=%s&limit=20' % kw)
    want = norm(title.replace('_', ''))
    for h in r.get('hits') or []:
        if norm(h.get('title')) == want:
            return {'source': 'makerworld', 'id': str(h['id']), 'name': h.get('title'),
                    'author': (h.get('designCreator') or {}).get('name'),
                    'url': 'https://makerworld.com/en/models/%s-%s' % (h['id'], h.get('slug')),
                    'imageUrl': makerworld_cover(h.get('cover'))}
    return None


def safe(fn):
    if OFFLINE:
        return None
    try:
        return fn()
    except Exception as e:  # network errors, bad JSON, ...
        print('WARNING: %s' % e, file=sys.stderr)
        return None


def resolve_build(b):
    d, hint = b['Dir'], b['Hint']
    n = os.path.basename(d)
    info = None
    if hint == 'thingiverse':
        tv = tv_readme(d)
        if tv:
            info = {'source': 'thingiverse', 'id': tv['Id'], 'name': tv['Name'], 'author': tv['Author'], 'url': tv['Url']}
        else:
            m = re.search(r'(\d{5,8})', n)
            if m:
                info = {'source': 'thingiverse', 'id': m.group(1), 'name': pretty(n),
                        'url': 'https://www.thingiverse.com/thing:' + m.group(1)}
    elif hint == 'printables':
        pid = printables_pdf_id(d)
        if pid:
            info = safe(lambda: printables_by_id(pid)) or {'source': 'printables', 'id': pid, 'url': 'https://www.printables.com/model/' + pid}
        else:
            slug = re.sub(r'-mo$', '', re.sub(r'-model_files$', '', n, flags=re.I), flags=re.I)
            info = safe(lambda: printables_search(slug.replace('-', ' '), slug))
        info = info or {'source': 'printables'}
    elif hint == 'makerworld':
        title = re.sub(r'_stls$', '', n, flags=re.I).replace('+', ' ')
        info = safe(lambda: makerworld_search(title)) or {'source': 'makerworld'}
    else:
        title = pretty(n)
        info = safe(lambda: printables_search(title, None)) or safe(lambda: makerworld_search(title)) or {'source': 'unknown'}
    return info


# ---------------------------------------------------------------- cache
def load_cache():
    if os.path.exists(CACHE_PATH):
        with open(CACHE_PATH, encoding='utf-8-sig') as f:
            return json.load(f)
    return {}


def save_cache(cache):
    ordered = {}
    for k in osort(cache.keys(), lambda s: s):
        e = cache[k]
        ordered[k] = {f: e[f] for f in osort([f for f in e if e[f] is not None], lambda s: s)}
    write_text(CACHE_PATH, json.dumps(ordered, indent=2, ensure_ascii=False) + '\n')


# ---------------------------------------------------------------- images
def img_name(rel_under_cat, ext):
    slug = re.sub(r'[^a-z0-9]+', '-', rel_under_cat.lower()).strip('-')
    if len(slug) > 70:
        slug = slug[:70].strip('-')
    h = hashlib.md5(rel_under_cat.encode('utf-8')).hexdigest()[:8]
    return '%s-%s%s' % (slug, h, ext) if slug else h + ext


def extract_3mf_thumb(path, dest):
    try:
        with zipfile.ZipFile(path) as z:
            entries = z.infolist()
            base = lambda e: e.filename.rsplit('/', 1)[-1]
            e = next((e for e in entries if e.filename.lower().startswith('auxiliaries/model pictures/') and e.file_size > 0
                      and re.search(r'\.(png|jpe?g|webp)$', base(e), re.I)), None)
            if not e:
                e = next((e for e in entries if re.match(r'^Metadata/(plate_1|thumbnail)\.png$', e.filename, re.I)), None)
            if not e:
                e = next((e for e in entries if re.match(r'^Metadata/.*\.png$', e.filename, re.I)
                          and not re.search(r'^(top|pick)_|_small', base(e), re.I)), None)
            if not e:
                return None
            out = dest[:len(dest) - len(ext_of(dest))] + ext_of(base(e)).lower()
            with z.open(e) as src, open(out, 'wb') as f:
                f.write(src.read())
            return out
    except Exception:
        return None


def pick_local_image(full):
    imgs = [f for f in all_files(full) if is_image(f) and os.path.getsize(f) > 2000]
    if not imgs:
        return None
    named = [f for f in imgs if not re.fullmatch(r'[0-9a-f]{32}', stem_of(os.path.basename(f)), re.I)]
    return (named or imgs)[0]


def get_preview(entry, cat_full, target_full, is_dir):
    rel_under_cat = rel(target_full)[len(entry['Category']):].lstrip('/')
    img_dir = os.path.join(cat_full, IMG_DIR)
    dest_base = os.path.join(img_dir, img_name(rel_under_cat, ''))
    existing = osort(glob.glob(glob.escape(dest_base) + '.*'), os.path.basename)
    if existing:
        return existing[0]
    info = entry['Info']
    if info.get('imageUrl') and not OFFLINE:
        os.makedirs(img_dir, exist_ok=True)
        out = dest_base + '.webp'
        try:
            download(info['imageUrl'], out)
            return out
        except Exception as e:
            print('WARNING: image download failed for %s: %s' % (info.get('url'), e), file=sys.stderr)
            if os.path.exists(out):
                os.remove(out)
    if is_dir:
        local = pick_local_image(target_full)
        if local:
            return local
        tmf = next((f for f in all_files(target_full) if ext_of(f).lower() == '.3mf'), None)
        if tmf:
            os.makedirs(img_dir, exist_ok=True)
            return extract_3mf_thumb(tmf, dest_base + '.png')
    elif ext_of(entry['File']).lower() == '.3mf':
        os.makedirs(img_dir, exist_ok=True)
        return extract_3mf_thumb(entry['File'], dest_base + '.png')
    return None


# ---------------------------------------------------------------- README rendering
def source_link(info, fallback_title):
    if info.get('url'):
        return '<a href="%s">%s</a>' % (html_enc(info['url']), SITE_NAME.get(info.get('source'), ''))
    q = escape_data(fallback_title)
    if info.get('source') == 'makerworld':
        return '<a href="https://makerworld.com/en/search/models?keyword=%s">Search MakerWorld</a>' % q
    if info.get('source') == 'printables':
        return '<a href="https://www.printables.com/search/models?q=%s">Search Printables</a>' % q
    return 'Source unknown'


def rel_from_cat(cat_full, path):
    return path[len(cat_full):].lstrip(os.sep).replace(os.sep, '/')


def write_readme(path, generated):
    if os.path.exists(path):
        old = read_text(path)
        if GEN_MARKER not in old:
            # keep the hand-written part; drop the generated title/marker lines and put the rest in a marked section
            body = '\n'.join(generated.split('\n')[4:])
            section = '%s\n%s\n<!-- builds:end -->' % (SEC_START, body.rstrip())
            kept = SEC_REGEX.sub('', old).rstrip()
            write_text(path, '%s\n\n%s\n' % (kept, section))
            return
    write_text(path, generated)


def main(argv=None):
    global OFFLINE
    ap = argparse.ArgumentParser(description='Generate the build gallery READMEs.')
    ap.add_argument('--refresh', action='store_true', help='re-query the websites for every non-manual entry')
    ap.add_argument('--offline', action='store_true', help="don't contact any website; use only the cache and local files")
    ap.add_argument('--list-only', action='store_true', help='just list the detected builds')
    args = ap.parse_args(argv)
    OFFLINE = args.offline
    _kids.clear(); _marker.clear()

    # ------------------------------------------------------------ discovery
    builds, loose, group_dirs = [], [], []
    categories = osort([e.path for e in os.scandir(REPO) if e.is_dir() and e.name.lower() not in SKIP_DIRS
                        and not e.name.startswith('.')], os.path.basename)
    split_roots = set()
    for pat in SPLIT_FOLDERS:
        for p in glob.glob(os.path.join(REPO, *pat.split('/'))):
            if os.path.isdir(p) and os.path.basename(p).lower() not in SKIP_DIRS:
                split_roots.add(rel(p).lower())

    def walk(d, in_split):
        dirs, files = kids(d)
        sub_names = {os.path.basename(c).lower() for c in dirs}
        for c in dirs:
            r = rel(c)
            is_split = r.lower() in split_roots
            hint = source_hint(c)
            if is_split or (not hint and has_marker_below(c)):
                group_dirs.append({'Rel': r, 'InSplit': in_split or is_split, 'IsSplit': is_split})
                walk(c, in_split or is_split)
            elif hint:
                builds.append({'Dir': c, 'Hint': hint, 'Rel': r})
            elif any(is_model(f) for f in all_files(c)):
                builds.append({'Dir': c, 'Hint': None, 'Rel': r})
        for f in files:
            if not is_model(f):
                continue
            base = stem_of(os.path.basename(f))
            if ext_of(f).lower() == '.zip' and (base.lower() in sub_names or re.sub(r'\(\d+\)$', '', base).lower() in sub_names):
                continue  # already extracted
            loose.append({'File': f, 'Rel': rel(f)})

    for cat in categories:
        walk(cat, NEST_EVERYWHERE)

    # README roots: every top-level category, every split folder, and every group that holds 2+ builds
    roots = [os.path.basename(c) for c in categories]
    for g in group_dirs:
        if g['IsSplit']:
            roots.append(g['Rel'])
        elif g['InSplit'] and sum(1 for b in builds if b['Rel'].startswith(g['Rel'] + '/')) >= 2:
            roots.append(g['Rel'])
    readme_roots = osort(list(dict.fromkeys(roots)), lambda s: s)
    roots_lower = {r.lower() for r in readme_roots}

    def owning_root(r):   # deepest README root that contains this path
        best = None
        for x in readme_roots:
            if r.startswith(x + '/') and (not best or len(x) > len(best)):
                best = x
        return best

    for e in builds + loose:
        e['Category'] = owning_root(e['Rel'])
    print('Found %d builds and %d loose files in %d categories' % (len(builds), len(loose), len(categories)))
    if args.list_only:
        for b in builds:
            print('%-12s %s' % (b['Hint'] or '?', b['Rel']))
        for l in loose:
            print('%-12s %s' % ('file', l['Rel']))
        return

    # ------------------------------------------------------------ resolve sources (cached)
    cache = load_cache()
    for i, b in enumerate(builds, 1):
        c = cache.get(b['Rel'])
        if c is not None and (c.get('manual') or not args.refresh):
            b['Info'] = c
            continue
        if i % 20 == 0:
            print('  resolving %d / %d' % (i, len(builds)))
        b['Info'] = cache[b['Rel']] = resolve_build(b)
    for l in loose:
        c = cache.get(l['Rel'])
        if c is not None and (c.get('manual') or not args.refresh):
            l['Info'] = c
            continue
        name = os.path.basename(l['File'])
        info = None
        if '+' in name:
            info = safe(lambda: makerworld_search(re.sub(r'\(\d+\)$', '', stem_of(name)).replace('+', ' ')))
        l['Info'] = cache[l['Rel']] = info or {'source': 'makerworld' if '+' in name else 'unknown'}
    save_cache(cache)

    # ------------------------------------------------------------ render
    def count_under(root):
        return sum(1 for e in builds + loose if e['Category'] and (e['Category'].lower() == root.lower() or e['Category'].startswith(root + '/')))

    def title_of(root):
        return pretty(root.split('/')[-1])

    def group_title(name, title):
        return ' / '.join(pretty(p) for p in name.split('/')) if name else title

    total = 0
    for root in readme_roots:
        cat_full = os.path.join(REPO, *root.split('/'))
        cb = [b for b in builds if b['Category'] and b['Category'].lower() == root.lower()]
        cl = [l for l in loose if l['Category'] and l['Category'].lower() == root.lower()]
        subs = [s for s in readme_roots if (owning_root(s) or '').lower() == root.lower() and count_under(s) > 0]
        if not cb and not cl and not subs:
            continue
        parent = owning_root(root)

        cards = []
        for b in cb:
            info = b['Info']
            rel_dir = rel_from_cat(cat_full, b['Dir'])
            dn = os.path.basename(b['Dir'])
            if info.get('name'):
                name = info['name']
            elif re.fullmatch(r'files|stls?|stl files', dn, re.I):
                name = '%s (%s)' % (pretty(os.path.basename(os.path.dirname(b['Dir']))), dn)
            else:
                name = pretty(dn)
            img = get_preview(b, cat_full, b['Dir'], True)
            cards.append({'Name': name, 'Group': posixpath.dirname(rel_dir), 'Link': enc(rel_dir),
                          'Img': enc(rel_from_cat(cat_full, img)) if img else None, 'Info': info,
                          'Fallback': pretty(dn), 'IsFile': False})
        for l in cl:
            info = l['Info']
            rel_file = rel_from_cat(cat_full, l['File'])
            img = get_preview(l, cat_full, l['File'], False)
            fn = os.path.basename(l['File'])
            name = info.get('name') or stem_of(fn).replace('+', ' ')
            cards.append({'Name': name, 'Group': posixpath.dirname(rel_file), 'Link': enc(rel_file),
                          'Img': enc(rel_from_cat(cat_full, img)) if img else None, 'Info': info,
                          'Fallback': name, 'IsFile': True, 'FileName': fn})

        out = []
        title = title_of(root)
        out += ['# ' + title, '']
        out += ['<!-- Generated by scripts/Update-Readmes.ps1 (Linux: scripts/update_readmes.py) - edit scripts/readme-sources.json and rerun instead of editing by hand. -->', '']
        crumbs, p = [], parent
        while p:
            up = len(root.split('/')) - len(p.split('/'))
            crumbs.insert(0, '[%s](%sREADME.md)' % (title_of(p), '../' * up))
            p = owning_root(p)
        crumbs.insert(0, '[Home](%sREADME.md)' % ('../' * len(root.split('/'))))
        out += ['%s / **%s**' % (' / '.join(crumbs), title), '']

        by_source = {}
        for c in cards:
            s = c['Info'].get('source') or ''
            by_source[s.lower()] = by_source.get(s.lower(), 0) + 1
        line = '%d builds' % len(cards)
        if by_source:
            line += ' &middot; ' + ' &middot; '.join('%d %s' % (by_source[s], SITE_NAME.get(s, 'unknown source'))
                                                     for s in osort(by_source, lambda s: s))
        if subs:
            line += ' &middot; %d collections (%d more builds)' % (len(subs), sum(count_under(s) for s in subs))
        out += [line, '']

        if subs:
            out += ['## Collections', '']
            for s in subs:
                rel_s = s[len(root) + 1:]
                label = ' / '.join(pretty(x) for x in rel_s.split('/'))
                out.append('- [%s](%s/README.md) - %d builds' % (label, enc(rel_s), count_under(s)))
            out.append('')

        groups = {}   # case-insensitive, first spelling wins (like Group-Object)
        for c in cards:
            k = c['Group'].lower()
            if k not in groups:
                groups[k] = (c['Group'], [])
            groups[k][1].append(c)
        groups = osort(list(groups.values()), lambda g: '1' + g[0] if g[0] else '0')

        if len(groups) > 1:
            out += ['## Contents', '']
            if subs:
                out.append('- [Collections](#collections)')
            for gname, gcards in groups:
                gt = group_title(gname, title)
                anchor = re.sub(r'[^\w \-]|_', '', gt.lower()).replace(' ', '-')
                out.append('- [%s](#%s) (%d)' % (gt, anchor, len(gcards)))
            out.append('')

        for gname, gcards in groups:
            out += ['## ' + group_title(gname, title), '']
            allc = osort(gcards, lambda c: '%s\0%s' % (c['Name'], c['Link']))
            items = [c for c in allc if not (c['IsFile'] and not c['Img'] and not c['Info'].get('url'))]
            plain = [c for c in allc if c['IsFile'] and not c['Img'] and not c['Info'].get('url')]
            if items:
                out.append('<table>')
            for r in range(0, len(items), 3):
                out.append('<tr>')
                for it in items[r:r + 3]:
                    out.append('<td width="33%" align="center" valign="top">')
                    if it['Img']:
                        out.append('<a href="%s"><img src="%s" width="240" alt="%s"></a><br>' % (it['Link'], it['Img'], html_enc(it['Name'])))
                    else:
                        out.append('<i>no preview</i><br>')
                    out.append('<b>%s</b><br>' % html_enc(it['Name']))
                    if it['Info'].get('author'):
                        out.append('<sub>by %s</sub><br>' % html_enc(it['Info']['author']))
                    repo_label = html_enc(it['FileName']) if it['IsFile'] else 'Repo folder'
                    out.append('%s &middot; <a href="%s">%s</a>' % (source_link(it['Info'], it['Fallback']), it['Link'], repo_label))
                    out.append('</td>')
                out.append('</tr>')
            if items:
                out += ['</table>', '']
            if plain:
                out += ['<details><summary>Other files in this folder (%d)</summary>' % len(plain), '']
                for p in osort(plain, lambda c: '%s\0%s' % (c['FileName'], c['Link'])):
                    out.append('- [%s](%s)' % (re.sub(r'([\[\]])', r'\\\1', p['FileName']), p['Link']))
                out += ['', '</details>', '']

        write_readme(os.path.join(cat_full, 'README.md'), '\n'.join(out) + '\n')
        total += len(cards)
        print('  %-50s %4d entries' % (root, len(cards)))
    print('Wrote READMEs for %d entries.' % total)

    # ------------------------------------------------------------ prune stale generated output
    for g in group_dirs:
        if g['Rel'].lower() in roots_lower:
            continue
        f = os.path.join(REPO, *g['Rel'].split('/'), 'README.md')
        if not os.path.exists(f):
            continue
        t = read_text(f)
        if GEN_MARKER in t:
            os.remove(f)
            print('  removed stale %s/README.md' % g['Rel'])
        elif SEC_REGEX.search(t):
            write_text(f, SEC_REGEX.sub('', t).rstrip() + '\n')
    for root_dir, dirs, _ in os.walk(REPO):
        dirs[:] = [d for d in dirs if not d.startswith('.')]
        for d in [d for d in dirs if d.lower() == IMG_DIR]:
            folder = os.path.join(root_dir, d)
            readme = os.path.join(root_dir, 'README.md')
            text = read_text(readme) if os.path.exists(readme) else ''
            for name in os.listdir(folder):
                p = os.path.join(folder, name)
                if os.path.isfile(p) and not name.startswith('.') and ('%s/%s' % (IMG_DIR, escape_data(name))) not in text:
                    os.remove(p)
            if not os.listdir(folder):
                os.rmdir(folder)

    # ------------------------------------------------------------ root index (between markers)
    root_readme = os.path.join(REPO, 'README.md')
    root_text = read_text(root_readme) if os.path.exists(root_readme) else '# 3d-print-files\n'
    idx = '<!-- categories:start -->\n## Categories\n\n'
    for cat in categories:
        if os.path.exists(os.path.join(cat, 'README.md')):
            n = os.path.basename(cat)
            idx += '- [%s](%s/README.md) - %d builds\n' % (pretty(n), enc(n), count_under(n))
    idx += '<!-- categories:end -->'
    rx = re.compile(r'(?s)<!-- categories:start -->.*<!-- categories:end -->')
    root_text = rx.sub(lambda m: idx, root_text) if rx.search(root_text) else root_text.rstrip() + '\n\n' + idx + '\n'
    write_text(root_readme, root_text)


